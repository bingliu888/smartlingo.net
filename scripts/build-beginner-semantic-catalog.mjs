import { readFileSync, writeFileSync } from "node:fs";

const plan = JSON.parse(readFileSync(new URL("../media-source/beginner-visual-concept-plan.json", import.meta.url), "utf8"));
const concepts = plan.concepts.map((concept, index) => ({
  ...concept,
  meaningsZh: concept.meaningsZh.filter(value => !/\bfaq\b/i.test(value)),
  mediaTier: index < plan.selectedAiConcepts ? "ai" : "semantic-svg",
  sheet: index < plan.selectedAiConcepts
    ? Math.floor(index / plan.sheetSize) + 1
    : Math.floor((index - plan.selectedAiConcepts) / plan.sheetSize) + 1,
  cell: index < plan.selectedAiConcepts ? index % plan.sheetSize : (index - plan.selectedAiConcepts) % plan.sheetSize,
}));

const source = `// Generated by scripts/build-beginner-semantic-catalog.mjs. Do not edit by hand.\n` +
  `export const BEGINNER_SEMANTIC_MEDIA_VERSION = ${JSON.stringify(plan.version)} as const;\n` +
  `export const BEGINNER_SEMANTIC_GRID_SIZE = 6 as const;\n` +
  `export const BEGINNER_SEMANTIC_CONCEPTS = ${JSON.stringify(concepts, null, 2)} as const;\n\n` +
  `export type BeginnerSemanticImageKey = (typeof BEGINNER_SEMANTIC_CONCEPTS)[number]["key"];\n`;

writeFileSync(new URL("../lib/smartlingo-semantic-media-catalog.ts", import.meta.url), source);

const sqlValue = value => `'${String(value).replaceAll("'", "''")}'`;
const mediaRows = Array.from({ length: Math.ceil(plan.selectedAiConcepts / plan.sheetSize) }, (_, sheetIndex) => {
  const sheet = sheetIndex + 1;
  const subjects = concepts.filter(concept => concept.mediaTier === "ai" && concept.sheet === sheet).map(concept => concept.key);
  const number = String(sheet).padStart(2, "0");
  return `(${[
    `beginner-semantic-vocabulary-sprite-${number}-2026-08-23`,
    `/images/smartcards/beginner-semantic-vocabulary-sprite-${number}-2026-08-23.png`,
    "image-sprite",
    "openai-image-generation",
    "semantic-expansion-2026-08-23",
    JSON.stringify(subjects),
    "Original SmartLingo 6x6 language-neutral beginner semantic picture sprite, ordered by shared cross-language frequency and difficulty priority.",
  ].map(sqlValue).join(",")},unixepoch(),unixepoch())`;
});
const fallbackCount = concepts.length - plan.selectedAiConcepts;
for (let sheetIndex = 0; sheetIndex < Math.ceil(fallbackCount / plan.sheetSize); sheetIndex += 1) {
  const sheet = sheetIndex + 1;
  const subjects = concepts.filter(concept => concept.mediaTier === "semantic-svg" && concept.sheet === sheet).map(concept => concept.key);
  const number = String(sheet).padStart(3, "0");
  mediaRows.push(`(${[
    `beginner-semantic-fallback-sprite-${number}-2026-08-23`,
    `/images/smartcards/beginner-semantic-fallback-sprite-${number}-2026-08-23.svg`,
    "image-sprite",
    "curated",
    "semantic-expansion-2026-08-23",
    JSON.stringify(subjects),
    "Original language-neutral SmartLingo semantic SVG micro-scenes for rare beginner concepts, with deterministic category iconography and no text.",
  ].map(sqlValue).join(",")},unixepoch(),unixepoch())`);
}
// Cloudflare D1 rejects a single multi-row statement once it crosses SQLite's
// remote statement-size limit. Keep each asset upsert independently retryable.
const mediaStatements = mediaRows.map(row =>
  `INSERT INTO smartlingo_learning_media_assets(asset_key,asset_path,media_kind,generation_source,release_id,subject_manifest_json,prompt_summary,reviewed_at,created_at) VALUES\n${row}\nON CONFLICT(asset_key) DO UPDATE SET asset_path=excluded.asset_path,release_id=excluded.release_id,subject_manifest_json=excluded.subject_manifest_json,reviewed_at=excluded.reviewed_at;`,
);
const migration = `${mediaStatements.join("\n\n")}\n\nPRAGMA optimize;\n`;
writeFileSync(new URL("../drizzle/0165_beginner_semantic_media.sql", import.meta.url), migration);
console.log(JSON.stringify({
  concepts: concepts.length,
  aiSheets: Math.ceil(plan.selectedAiConcepts / plan.sheetSize),
  semanticSvgSheets: Math.ceil(fallbackCount / plan.sheetSize),
  version: plan.version,
}));
