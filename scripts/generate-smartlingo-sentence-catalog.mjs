import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  SMARTLINGO_SENTENCE_CONTENT_VERSION,
  buildCourseSentenceBank,
  tokenizeSentence,
} from "../lib/smartlingo-sentence-exercises.ts";

const languages = ["zh", "en", "es", "ja", "ko", "fr", "de", "ru", "it", "pt", "ar", "hi"];
const levels = ["beginner", "intermediate", "advanced"];
const output = fileURLToPath(new URL("../drizzle/0156_graded_scenario_sentence_catalog.sql", import.meta.url));
const quote = value => `'${String(value).replaceAll("'", "''")}'`;

const rows = languages.flatMap(language => levels.flatMap(level =>
  buildCourseSentenceBank(language, level).map(item => ({
    ...item,
    answerTokens: tokenizeSentence(item.targetSentence, language),
  })),
));

if (rows.length !== 4320) throw new Error(`Expected 4,320 sentence rows, received ${rows.length}`);

const statements = rows.map(item => `INSERT INTO smartlingo_scenario_sentences
  (id,content_version,target_language,level,cefr_band,difficulty,frequency_degree,sequence,scenario_key,function_key,target_sentence,translation_zh,translation_en,answer_tokens,anchor_vocabulary,source_type,review_status,created_at,updated_at)
VALUES(${[
  item.id, item.contentVersion, item.language, item.level, item.cefrBand, item.difficulty,
  item.frequencyDegree, item.sequence, item.scenario, item.functionId, item.targetSentence,
  item.translation.zh, item.translation.en, JSON.stringify(item.answerTokens), item.anchorVocabulary,
  "smartlingo_original_cefr_aligned", "published",
].map((value, index) => index >= 5 && index <= 7 ? value : quote(value)).join(",")},unixepoch(),unixepoch());`).join("\n");

const sql = `-- Generated by scripts/generate-smartlingo-sentence-catalog.mjs.
-- ${SMARTLINGO_SENTENCE_CONTENT_VERSION}: 12 languages × 3 levels × 12 scenarios × 10 communicative functions.
CREATE TABLE IF NOT EXISTS smartlingo_scenario_sentences (
  id text PRIMARY KEY NOT NULL,
  content_version text NOT NULL,
  target_language text NOT NULL CHECK(target_language IN ('zh','en','es','ja','ko','fr','de','ru','it','pt','ar','hi')),
  level text NOT NULL CHECK(level IN ('beginner','intermediate','advanced')),
  cefr_band text NOT NULL,
  difficulty integer NOT NULL CHECK(difficulty BETWEEN 1 AND 5),
  frequency_degree integer NOT NULL CHECK(frequency_degree BETWEEN 1 AND 10),
  sequence integer NOT NULL CHECK(sequence BETWEEN 1 AND 120),
  scenario_key text NOT NULL,
  function_key text NOT NULL,
  target_sentence text NOT NULL,
  translation_zh text NOT NULL,
  translation_en text NOT NULL,
  answer_tokens text NOT NULL CHECK(json_valid(answer_tokens) AND json_type(answer_tokens)='array' AND json_array_length(answer_tokens)>=2),
  anchor_vocabulary text NOT NULL,
  source_type text NOT NULL,
  review_status text NOT NULL CHECK(review_status IN ('draft','reviewed','published')),
  created_at integer NOT NULL,
  updated_at integer NOT NULL,
  UNIQUE(content_version,target_language,level,sequence)
);
CREATE INDEX IF NOT EXISTS smartlingo_scenario_sentence_course_idx
  ON smartlingo_scenario_sentences(target_language,level,review_status,sequence);
CREATE INDEX IF NOT EXISTS smartlingo_scenario_sentence_scene_idx
  ON smartlingo_scenario_sentences(target_language,level,scenario_key,function_key);
DELETE FROM smartlingo_scenario_sentences WHERE content_version=${quote(SMARTLINGO_SENTENCE_CONTENT_VERSION)};
${statements}
`;

writeFileSync(output, sql);
console.log(`Wrote ${rows.length} graded scenario sentences to ${output}`);
