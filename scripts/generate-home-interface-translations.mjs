import fs from "node:fs/promises";
import vm from "node:vm";

const sourcePath = new URL("../app/[lang]/page.tsx", import.meta.url);
const outputPath = new URL("../lib/home-interface-translations.generated.ts", import.meta.url);
const requested = process.argv.slice(2);
const targets = requested.length ? requested : ["ja", "ko", "es", "fr", "de", "ru", "it", "pt", "ar", "hi"];

const source = await fs.readFile(sourcePath, "utf8");
const start = source.indexOf("const copy = ") + "const copy = ".length;
const end = source.indexOf("\n\nexport async function", start);
if (start < "const copy = ".length || end < 0) throw new Error("Unable to locate homepage copy object");
const expression = source.slice(start, end).replace(/\s+as const;\s*$/, "");
const copy = vm.runInNewContext(`(${expression})`);

const strings = [];
function collect(value) {
  if (typeof value === "string") strings.push(value);
  else if (Array.isArray(value)) value.forEach(collect);
  else if (value && typeof value === "object") Object.values(value).forEach(collect);
}
collect(copy.en);
const unique = [...new Set(strings)].filter(value => !/^\d+$/.test(value));

async function translateBatch(batch, target) {
  const separator = "\n@@@\n";
  const endpoint = new URL("https://clients5.google.com/translate_a/t");
  endpoint.searchParams.set("client", "dict-chrome-ex");
  endpoint.searchParams.set("sl", "en");
  endpoint.searchParams.set("tl", target);
  endpoint.searchParams.set("q", batch.join(separator));
  const response = await fetch(endpoint, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${target} translation HTTP ${response.status}`);
  const payload = await response.json();
  const translatedText = Array.isArray(payload) ? payload[0] : "";
  if (typeof translatedText !== "string") throw new Error(`${target} translation returned an invalid payload`);
  const translated = translatedText.split(separator);
  if (translated.length !== batch.length) throw new Error(`${target} translation returned ${translated.length}/${batch.length} segments`);
  return translated;
}

const wait = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
async function translateBatchWithRetry(batch, target) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try { return await translateBatch(batch, target); }
    catch (error) {
      if (attempt === 4) throw error;
      await wait(2000 * (attempt + 1));
    }
  }
}

function batches(values, maximumCharacters = 420) {
  const result = []; let current = []; let size = 0;
  for (const value of values) {
    if (current.length && size + value.length + 5 > maximumCharacters) { result.push(current); current = []; size = 0; }
    current.push(value); size += value.length + 5;
  }
  if (current.length) result.push(current);
  return result;
}

let existing = {};
try {
  const generated = await fs.readFile(outputPath, "utf8");
  const json = generated.match(/homeInterfaceTranslations[^=]*=\s*([\s\S]*?);(?:\n|$)/)?.[1];
  if (json) existing = JSON.parse(json);
} catch {}

for (const target of targets) {
  const translated = {};
  for (const batch of batches(unique)) {
    const results = await translateBatchWithRetry(batch, target);
    batch.forEach((value, index) => { translated[value] = results[index]; });
    await wait(350);
  }
  existing[target] = translated;
  process.stdout.write(`Generated ${target}: ${Object.keys(translated).length} strings\n`);
  const checkpoint = JSON.stringify(existing, null, 2);
  await fs.writeFile(outputPath, `// Generated by scripts/generate-home-interface-translations.mjs.\n// Public interface copy only; review changes before release.\nexport const homeInterfaceTranslations: Record<string, Record<string, string>> = ${checkpoint};\n`);
}

const json = JSON.stringify(existing, null, 2);
const file = `// Generated by scripts/generate-home-interface-translations.mjs.\n` +
  `// Public interface copy only; review changes before release.\n` +
  `export const homeInterfaceTranslations: Record<string, Record<string, string>> = ${json};\n`;
await fs.writeFile(outputPath, file);
